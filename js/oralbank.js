/* ============================================================================
   oralbank.js  —  SOURCE OF TRUTH for the CHECKRIDE ORAL mode.

   Private Pilot (Airplane, single-engine land) practical-test oral, C172S
   (G1000), organised by the ACS Areas of Operation that are examined on the
   ground. The mode is run by a HELPER who is not a pilot: they read `ask`
   aloud, tick the points they hear, and the app grades. So every point is
   written to be recognised by ear by someone with no aviation background.

   ORAL_AREAS       the areas, in the order the examiner usually works:
     { id, name, acs, sub, color }
   ORAL_QUESTIONS   the bank:
     { id, area, lvl, kind, ask, show?, gloss, say?, pts, need?, no?, answer, ref, fu? }
       id     unique, stable — history and the misses deck key on it; don't rename casually
       area   an ORAL_AREAS id
       lvl    1 core (asked on nearly every checkride) · 2 standard · 3 deep dive
       kind   "recall" (a fact or list) · "explain" (how / why) · "scenario" (apply it)
       ask    what the helper reads aloud, word for word
       show   optional text handed to the STUDENT to read (a METAR, a loading table) —
              the helper is not expected to read it out
       gloss  plain English for the helper: what this is about and why it matters
       say    [[term, how to say it]] pronunciation help for anything in `ask`/`pts`
       pts    the listening checklist: [{ k, t, hear, must }]
                k     key, unique within the question (follow-up triggers use it)
                t     the point, in words a non-pilot can match by ear
                hear  other ways the student may say it — any of these counts
                must  true = needed for a pass; false = bonus depth
       need   how many `must` points make a pass (default: all of them). Used for long
              lists where the examiner accepts most-of.
       no     red flags: things that are WRONG if the student says them. One ticked caps
              the grade at "needs work".
       answer the model answer shown to the student after grading
       ref    where to study it
       fu     follow-ups: [{ when, ask, show?, gloss?, say?, pts, need?, no?, answer, ref? }]
                when  "always"  offer regardless
                      "sat"     the main question passed — dig deeper
                      "unsat"   it did not pass — a second chance from another angle
                      "miss:k"  must-point k was not ticked — prompt for exactly that
              ids are assigned at load: q.id + "/" + (index + 1).
   In every scenario the answer must be reachable from what `ask`/`show` states.

   Sources: FAA-S-ACS-6C (Private Pilot — Airplane ACS); 14 CFR Parts 1, 21, 39,
   43, 61, 68, 91 (sections cited per question) and NTSB 830; AIM chapters 2–8;
   PHAK (FAA-H-8083-25); AFH (FAA-H-8083-3C); Aviation Weather Handbook
   (FAA-H-8083-28); AC 90-66, AC 61-142; C172S NAV III POH sections 2–7.
   C172S figures already used elsewhere in the app are repeated unchanged: Vr 55,
   Vx 62, Vy 74, Va 105/98/90, Vfe 110/85, best glide 68 KIAS, 56/53 gal, 8 qt,
   28 V / 24 V / 60 A, LOW VOLTS 24.5 V, mag check 1,800 / 150 / 50. Added here from
   the POH as quoted in training material: Vs0 40, Vs1 48, Vno 129, Vne 163 KIAS,
   15 kt demonstrated crosswind, 2,550 lb (2,558 ramp, 2,200 utility), baggage
   120 / 50 / 120 lb, 5 qt minimum oil, the section 5 wind and grass corrections.
   The school's own POH and checklists govern; where schools or examiners differ,
   the point says so. Emergency flows follow the school's placard as drilled in
   emergencies.js (including its 68 KIAS engine-failure speed where the POH
   prints 70).
   ========================================================================== */

